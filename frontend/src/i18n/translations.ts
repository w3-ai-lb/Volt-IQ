/**
 * Built once at module load: one dictionary per language, from the rows above.
 * `t()` then does a single object lookup per call, with no per-call work.
 *
 * Arabic is merged in from its own file rather than added as a seventh column.
 * It arrived after this catalogue was written, and widening four hundred rows
 * would have rewritten every line here to no purpose. See i18n/arabic.ts.
 */
export const TRANSLATIONS: Record<string, Record<string, string>> = {
  ...Object.fromEntries(
    ORDER.map((code, index) => [
      code,
      Object.fromEntries(
        Object.entries(CATALOGUE).map(([english, row]) => [english, row[index]]),
      ),
    ]),
  ),
  ar: ARABIC,
};

/**
 * Phrases that exist in the five-language catalogue but have no Arabic entry.
 * Exported so a test can assert it is empty: without it a gap would show up as
 * an English word sitting in the middle of an Arabic page, which is the kind
 * of thing nobody notices until a demo.
 */
export const MISSING_ARABIC: string[] = Object.keys(CATALOGUE).filter((key) => !(key in ARABIC));

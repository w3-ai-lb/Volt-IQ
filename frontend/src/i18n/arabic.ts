/**
 * Arabic translations, keyed by the same English source text as the rest of
 * the catalogue.
 *
 * WHY THIS IS ITS OWN FILE
 * ------------------------
 * The other six languages live in translations.ts as rows of five, which keeps
 * a gap visible on the line where it happens. Arabic arrived after that file
 * was written, and appending a seventh column to four hundred rows would have
 * rewritten every line of it for no benefit. A separate map merges in at the
 * bottom of translations.ts and reads the same way.
 *
 * Arabic is also the first right-to-left language in the platform. The strings
 * themselves need nothing special for that: the mirroring is done by the `dir`
 * attribute on <html>, set in i18n/t.ts, and by the logical CSS properties the
 * components use. See directionOf() and slideFrom() there.
 *
 * A note on the numerals: Western digits (1, 2, 3) are used throughout rather
 * than Eastern Arabic ones (١, ٢, ٣). Both are correct Arabic, and Lebanon,
 * along with the rest of the Levant and North Africa, writes Western digits in
 * everyday use, including on utility bills. Figures also arrive from the API
 * already formatted, so switching only the interface would leave the page
 * mixing two numeral systems.
 */


"""
Which rows did we invent, and which came from the supervisor?

    python -m scripts.data_provenance                  # report
    python -m scripts.data_provenance --purge-demo     # remove what we invented

WHY THIS EXISTS
---------------
The database currently holds two kinds of record and they look identical from
the inside. Eighteen customers called Rami Khoury and Lara Awad, with 48,640
consumption readings, were generated by `app/pipeline/seed.py` as a stand-in
while there was no real data. Three hundred subscribers, twelve zones and seven
generators came from the supervisor's files.

Nothing in a report may come from the first group. A figure quoted at a defence
has to be traceable to a file somebody sent, and "it came from our seeder"
is not that. The trouble is that a query across the database does not
distinguish them, and the platform's own admin dashboard still reads the
invented ones.

So this names the boundary explicitly, and can remove one side of it.

FOUR TIERS, WITH DIFFERENT FUTURES
----------------------------------
1. INVENTED BY US, and now superseded. The seeded customers, their consumption,
   bills and payments. They were a placeholder for exactly the data that has
   since arrived. They go.

2. DEMO CREDENTIALS. admin@nxttrn.com / admin123 and the rest. These must not
   survive into anything real, whatever happens to the records around them.
   `scripts/create_admin.py` is what replaces them.

3. THE SUPERVISOR'S DATASET. He calls it fake, and it is synthetic, but he
   built it from their live system and it is what the work is graded against.
   It stays until the real InteliMonitor export and the real CRM extract
   arrive. It is not a placeholder we chose.

4. GENERATED TO HIS INSTRUCTION, on 18 August: the real customer records are
   postponed while the team deals with maintenance faults, so generate data
   that reflects the real business context and match the CRM project's shape.
   That is `app/pipeline/identities.py`, and it is a narrower thing than tier
   1 in a way that matters. It generates ONLY the identity, name, email,
   phone, street, coordinate, for subscribers whose file gives none.
   Everything countable on those records is measured from his own data:
   consumption from the meter readings, balance from the invoices and
   payments, region, plan and status from the subscription. Tier 1 invented
   the numbers too, which is why tier 1 goes and this stays.

   Forty-five of the names are not invented here either: they are read out of
   the customer-side project's own seed, data/crm/customer_side_seed_data.sql,
   and each is placed on a subscriber in the zone the CRM puts that person in.
   The other 255 are built from the same name pools and address format. What
   was deliberately NOT taken from that file is its readings, invoices and
   payments: they cover the same twelve zones over a different year than the
   supervisor's export, and two energy totals behind one zone is not a merge,
   it is two answers.

   These carry customer_id GEN- and an @generated.local address, so the two
   are told apart by a rule rather than by memory, and --purge-demo leaves
   them alone.

The schema of Project 1 is not in any of these tiers. The supervisor asked for
the two data sources to be merged, not for the CRM to be deleted.
"""


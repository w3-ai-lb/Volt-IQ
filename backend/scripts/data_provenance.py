def _count(db: Session, entry) -> int:
    """Rows belonging to one tier, which is not always the whole table."""
    model, _provenance, _source = entry[0], entry[1], entry[2]
    if len(entry) > 3 and entry[3] is not None:
        return entry[3](db).count()
    return db.query(func.count()).select_from(model).scalar() or 0


def report(db: Session) -> int:
    print("\n" + "=" * 78)
    print("  WHERE EVERY ROW IN THIS DATABASE CAME FROM")
    print("=" * 78)

    totals = {SEEDED: 0, SUPPLIED: 0, DERIVED: 0, GENERATED: 0, CUSTOMER_ACTIVITY: 0}
    for group in (SEEDED, SUPPLIED, DERIVED, GENERATED, CUSTOMER_ACTIVITY):
        print(f"\n  {group.upper()}")
        print("  " + "-" * 74)
        for entry in TABLES:
            model, provenance, source = entry[0], entry[1], entry[2]
            if provenance != group:
                continue
            n = _count(db, entry)
            totals[group] += n
            flag = "" if n else "   (empty)"
            print(f"    {model.__tablename__:<26} {n:>8,}   <- {source}{flag}")
        if group is GENERATED:
            print("      of each record: name, email, phone, street and coordinate are")
            print("      generated; consumption, balance, region, plan, status and start")
            print("      date are measured from his own readings, invoices and payments.")
            print("      45 of the names come from the CRM project's own seed file, each")
            print("      placed on a subscriber in the zone the CRM puts that person in.")

    print("\n  " + "-" * 74)
    print(f"    {'invented by us':<26} {totals[SEEDED]:>8,}")
    print(f"    {'from the supervisor':<26} {totals[SUPPLIED]:>8,}")
    print(f"    {'derived':<26} {totals[DERIVED]:>8,}")
    print(f"    {'generated to instruction':<26} {totals[GENERATED]:>8,}")
    print(f"    {'customer activity':<26} {totals[CUSTOMER_ACTIVITY]:>8,}")

    # --- stale replies, which a code fix cannot reach ------------------------
    # The chatbot stores what it said. When the currency was corrected, every
    # reply already written stayed as written, including "your current bill is
    # $14,761,123.00", because a log is a record of what was said, not a live
    # view that re-renders. Correct behaviour, wrong figure, sitting where a
    # customer can open it. Reported here rather than silently rewritten.
    stale = (
        db.query(func.count())
        .select_from(ChatMessage)
        .filter(ChatMessage.content.like("%$%"))
        .scalar()
        or 0
    )
    if stale:
        print(f"\n  {stale} stored chat repl(ies) contain a dollar amount, written before")
        print("  the currency was corrected. They are a log of what was said, so nothing")
        print("  rewrites them. Clear the test conversations with:")
        print("      python -m scripts.data_provenance --clear-chat")

    other = _real_customers(db).count()
    if other:
        print(f"\n    {other} customer record(s) match none of these rules. They were created")
        print("    by hand or by registration, so nothing here will remove them:")
        for row in _real_customers(db).limit(5):
            print(f"      {row.customer_id:<12} {row.name:<22} {row.email}")

    demo = _seeded_customers(db).count()
    signin = _seeded_customers(db).filter(Customer.password_hash != "").count()
    if demo:
        print("\n  ACCOUNTS")
        print("  " + "-" * 74)
        print(f"    {demo} seeded customer records, of which {signin} can be signed into.")
        for row in _seeded_customers(db).filter(Customer.password_hash != "").limit(5):
            print(f"      {row.customer_id:<12} {row.name:<22} {row.email}")
        print("\n    These are demo credentials. They must not exist in anything real.")
        print("    Replace with: python -m scripts.create_admin --email you@nxttrn.com")

    if totals[SEEDED]:
        print("\n  WHAT THIS MEANS FOR THE REPORT")
        print("  " + "-" * 74)
        print("    No figure quoted anywhere may come from the first group. They were a")
        print("    stand-in for data that has now arrived. The platform's own admin")
        print("    dashboard still reads them, so it is showing invented numbers.")
        print("\n    Remove them with:  python -m scripts.data_provenance --purge-demo")
        if totals[GENERATED]:
            print("    That leaves the generated identities in place. They are not the same")
            print("    thing: the supervisor asked for those, and their figures are his.")
    print()
    return 0


def purge(db: Session, assume_yes: bool) -> int:
    counts = {}
    for entry in TABLES:
        if entry[1] == SEEDED:
            counts[entry[0].__tablename__] = _count(db, entry)

    total = sum(counts.values())
    if not total:
        print("Nothing to remove: no seeded records are left.")
        return 0

    print("\nThis will permanently delete the records our seeder invented:\n")
    for table, n in counts.items():
        if n:
            print(f"    {table:<26} {n:>8,}")
    print(f"    {'TOTAL':<26} {total:>8,}\n")
    print("  The supervisor's data is NOT touched: subscribers, zones, generators,")
    print("  telemetry, readings, invoices and payments all stay.\n")
    generated = _generated_customers(db).count()
    if generated:
        print(f"  The {generated} generated identities (GEN-...) also stay. He asked for those,")
        print("  and every figure on them is measured from his own data.\n")
    print("  tests/test_api.py signs in as the demo customer and will fail after")
    print("  this. That is correct: those tests describe a demo, not the product.\n")

    # --- the two ways this leaves somebody stuck, checked rather than warned --
    #
    # Purging is meant to leave the product standing on the supervisor's data.
    # It only does that if the customer records exist first. Run in the wrong
    # order it empties the portal instead, and the person running it finds out
    # by opening a blank Customers page rather than by reading a caveat.
    blocked = []
    if not generated:
        blocked.append(
            "No customer records exist yet (no GEN- ids).\n"
            "       The supervisor's subscribers.csv carries no names, so removing the\n"
            "       demo now would leave the portal with nothing at all to show.\n"
            "       Run this first, then come back:\n"
            "           python -m app.pipeline.identities\n"
            "           python -m app.pipeline.portal"
        )
    if not _real_customers(db).filter(Customer.role == "admin").count():
        blocked.append(
            "There is no administrator other than the demo one.\n"
            "       admin@nxttrn.com is about to be deleted, and nothing would be\n"
            "       left to sign in with. Create yours first:\n"
            '           python -m scripts.create_admin --email you@nxttrn.com --name "Your Name"'
        )

    if blocked:
        print("  NOT REMOVING ANYTHING YET\n")
        for index, problem in enumerate(blocked, start=1):
            print(f"    {index}. {problem}\n")
        print("  Nothing was changed. Re-run this once the above is done.\n")
        return 1

    if not assume_yes:
        try:
            answer = input('Type "delete" to continue, anything else to stop: ')
        except EOFError:
            print("No confirmation given. Nothing was changed.")
            return 1
        if answer.strip().lower() != "delete":
            print("Stopped. Nothing was changed.")
            return 1

    # Children first: the seeded customer rows are the parent of most of this,
    # and cascade behaviour differs between SQLite and PostgreSQL. A tier that
    # shares its table with another is deleted through its own filter, never
    # by emptying the table, which is what keeps the GEN- records safe here.
    for entry in reversed(TABLES):
        model, provenance = entry[0], entry[1]
        if provenance != SEEDED:
            continue
        if len(entry) > 3 and entry[3] is not None:
            entry[3](db).delete(synchronize_session=False)
        else:
            db.query(model).delete()
    db.commit()

    print(f"\nRemoved {total:,} invented records.")
    remaining = _real_customers(db).filter(Customer.role == "admin").all()
    if remaining:
        print("Sign in with the administrator you created:")
        for row in remaining:
            print(f"    {row.email}")
    print(f"{_generated_customers(db).count()} customer records remain, all built from")
    print("the supervisor's own readings, invoices and payments.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Report or remove invented demo data.")
    parser.add_argument("--purge-demo", action="store_true",
                        help="Delete the records our seeder invented. The supervisor's data stays.")
    parser.add_argument("--yes", action="store_true", help="Skip the confirmation prompt.")
    parser.add_argument("--clear-chat", action="store_true",
                        help="Delete stored chat conversations. Test transcripts only; "
                             "the supervisor's data is untouched.")
    args = parser.parse_args()

    # Whole customer records are read below: first add any column this version
    # of the code expects, as the server does when it starts (app/database.py).
    add_missing_columns()
    db = SessionLocal()
    try:
        if args.clear_chat:
            messages = db.query(ChatMessage).delete()
            conversations = db.query(ChatConversation).delete()
            db.commit()
            print(f"Removed {messages:,} chat message(s) in {conversations:,} conversation(s).")
            print("Only the transcripts. No reading, invoice, payment or customer was touched.")
            return 0
        return purge(db, args.yes) if args.purge_demo else report(db)
    finally:
        db.close()


if __name__ == "__main__":
    raise SystemExit(main())

# How a seeded account is recognised. These are the seeder's own conventions,
# written down here so the rule is inspectable rather than implied: CUST-0001...,
# the unclaimed MTR- records, and its single administrator.
#
# TWO PATTERNS WERE REMOVED FROM THIS RULE, AND THE REASON MATTERS
# ---------------------------------------------------------------
# It used to match `ADMIN-0%` and `%@nxttrn.com` as well. Both were too wide,
# and together they deleted the thing the purge instructions tell you to make.
#
# `scripts/create_admin.py` numbers administrators ADMIN-001, ADMIN-002 and so
# on, so a real administrator created after the demo one matched `ADMIN-0%` and
# was removed by the next purge. And nxttrn.com is the company's own domain, 
# the printed instruction is literally `--email you@nxttrn.com`, so a real
# account at that domain matched too. Create your administrator, purge, and you
# were locked out of your own system with no obvious cause.
#
# The seeder makes exactly one administrator, ADMIN-001 / admin@nxttrn.com (see
# ADMIN in app/pipeline/seed.py). Matching it exactly is enough, and it is the
# only rule here that cannot catch something real by accident.
SEEDED_ADMIN_EMAIL = "admin@nxttrn.com"


def _seeded_customers(db: Session):
    return db.query(Customer).filter(
        or_(
            Customer.customer_id.like("CUST-%"),
            Customer.customer_id.like("MTR-%"),
            Customer.email == SEEDED_ADMIN_EMAIL,
            Customer.email.like("unclaimed.%"),
        )
    )


def _generated_customers(db: Session):
    """The identities written for the supervisor's own subscribers."""
    return db.query(Customer).filter(Customer.customer_id.like("GEN-%"))


# `consumption`, `bills` and `payments` each hold two tiers now: the rows our
# seeder invented, and the rows app/pipeline/portal.py projected out of the
# supervisor's readings and invoices so the portal screens read his data. The
# prefixes are imported rather than retyped, so the two modules cannot drift.
def _projected_consumption(db: Session):
    return db.query(Consumption).filter(Consumption.customer_id.like("GEN-%"))


def _projected_bills(db: Session):
    return db.query(Bill).filter(Bill.bill_id.like(f"{BILL_PREFIX}%"))


def _projected_payments(db: Session):
    return db.query(Payment).filter(Payment.payment_id.like(f"{PAYMENT_PREFIX}%"))


def _seeded_consumption(db: Session):
    return db.query(Consumption).filter(~Consumption.customer_id.like("GEN-%"))


def _seeded_bills(db: Session):
    return db.query(Bill).filter(~Bill.bill_id.like(f"{BILL_PREFIX}%"))


def _seeded_payments(db: Session):
    """
    Payments our seeder invented: not the pipeline's, and not a customer's.

    THE THIRD TIME THIS SHAPE OF MISTAKE APPEARED
    ---------------------------------------------
    "Anything without the pipeline's PAY-P prefix" also catches every payment a
    real subscriber records through the Pay button, which carries PAY-000123.
    Six of them existed the first time verify_purge ran after that button
    started working, and the purge took all six.

    A payment is money the provider actually received. Losing the record of one
    is the most expensive row in this database to lose, and it does not come
    back: nothing recomputes it.
    """
    return db.query(Payment).filter(
        ~Payment.payment_id.like(f"{PAYMENT_PREFIX}%"),
        ~Payment.customer_id.like("GEN-%"),
    )


def _customer_payments(db: Session):
    """Recorded by a real subscriber through the Pay button on the portal."""
    return db.query(Payment).filter(
        ~Payment.payment_id.like(f"{PAYMENT_PREFIX}%"),
        Payment.customer_id.like("GEN-%"),
    )


